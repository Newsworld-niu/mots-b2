/** Deterministic Mulberry32-style PRNG returning floats in `[0, 1)`. */
function createRng(seed: number): () => number {
  let x = (Math.floor(seed) ^ 0x9e3779b9) >>> 0;
  return () => {
    x = (Math.imul(x ^ (x >>> 15), 2246822519) + 0x6d2b79f5) >>> 0;
    return x / 4294967296;
  };
}

function pickFromPool<T>(pool: readonly T[], count: number, rnd: () => number): T[] {
  const scored = pool.map((item, idx) => ({ item, key: rnd() + idx * 1e-7 }));
  scored.sort((a, b) => a.key - b.key);
  return scored.slice(0, count).map((s) => s.item);
}

/**
 * Deterministically sample a stratified grammar sprint in ascending difficulty (`1 -> 6`):
 * - `"tcf"`: 18 `"structure"` items (3 per difficulty band `1..6`).
 * - `"tef"`: 40 stratified `"structure" + "lexique" + "error"` items across difficulty bands `1..6`.
 */
export function drawGrammarSprint(mode: SprintMode, seed = 1): GrammarSprintItem[] {
  const rnd = createRng(seed);
  if (mode === "tcf") {
    const out: GrammarSprintItem[] = [];
    for (const d of [1, 2, 3, 4, 5, 6] as const) {
      const band = GRAMMAR_SPRINT_BANK.filter((it) => it.category === "structure" && it.difficulty === d);
      out.push(...pickFromPool(band, 3, rnd));
    }
    return out;
  }

  // TEF: 40 items across difficulties 1..6 ([6, 6, 7, 7, 7, 7] = 40), preserving structure + lexique + error mix
  const quotas: Record<SprintDifficulty, { structure: number; lexique: number; error: number }> = {
    1: { structure: 3, lexique: 2, error: 1 }, // 6
    2: { structure: 3, lexique: 2, error: 1 }, // 6
    3: { structure: 4, lexique: 2, error: 1 }, // 7
    4: { structure: 4, lexique: 2, error: 1 }, // 7
    5: { structure: 3, lexique: 2, error: 2 }, // 7
    6: { structure: 3, lexique: 2, error: 2 }, // 7
  };
  const out: GrammarSprintItem[] = [];
  for (const d of [1, 2, 3, 4, 5, 6] as const) {
    const q = quotas[d];
    const sItems = pickFromPool(
      GRAMMAR_SPRINT_BANK.filter((it) => it.difficulty === d && it.category === "structure"),
      q.structure,
      rnd,
    );
    const lItems = pickFromPool(
      GRAMMAR_SPRINT_BANK.filter((it) => it.difficulty === d && it.category === "lexique"),
      q.lexique,
      rnd,
    );
    const eItems = pickFromPool(
      GRAMMAR_SPRINT_BANK.filter((it) => it.difficulty === d && it.category === "error"),
      q.error,
      rnd,
    );
    // Shuffle within the same difficulty band so categories interleave naturally while keeping ascending difficulty
    out.push(...pickFromPool([...sItems, ...lItems, ...eItems], q.structure + q.lexique + q.error, rnd));
  }
  return out;
}
