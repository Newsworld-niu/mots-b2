export function checkContextConjugation(
  item: ContextConjItem,
  chosenTense: ConjTense | null,
  typedForm: string,
): {
  tenseOk: boolean;
  formOk: boolean;
  accentOnly: boolean;
  canonical: string;
  orthographyHint: string | null;
} {
  const verdict = checkAnswer(typedForm, [...item.answers]);
  return {
    tenseOk: chosenTense === item.tense,
    formOk: verdict === "right",
    accentOnly: verdict === "accent",
    canonical: item.answers[0],
    orthographyHint: verdict === "wrong" ? explainOrthographyError(typedForm, [...item.answers]) : null,
  };
}
