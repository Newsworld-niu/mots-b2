def main():
    rows = list(csv.DictReader(open(LIST, encoding="utf-8")))
    lex = json.load(open(LEX, encoding="utf-8")); by = {e["id"]: e for e in lex["entries"]}
    applied = 0; skipped = []
    for r, zh in zip(rows[:len(T)], T):
        e = by.get(r["id"])
        if not e: skipped.append((r["id"], "missing")); continue
        idx = int(r["idx"])
        ex = e.get("examples", [])
        if idx < len(ex) and ex[idx].get("fr") == r["fr"] and not ex[idx].get("zh", "").strip():
            ex[idx]["zh"] = zh; applied += 1
        else:
            skipped.append((r["id"], "mismatch"))
    json.dump(lex, open(LEX, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("applied", applied, "skipped", len(skipped))

if __name__ == "__main__":
    main()
