# Read missing list to get pos/topic/lesson mapping
with open("scripts/batch/lesson09-10/missing-zh-list.txt", encoding="utf-8") as f:
    rows = []
    for line in f:
        line = line.strip()
        if not line:
            continue
        parts = line.split("\t")
        lemma, pos, topic, lessons = parts[0], parts[1], parts[2], parts[3]
        zh = ZH.get(lemma, "")
        if not zh:
            continue
        for lesson in lessons.split(","):
            chapter = "LES VÊTEMENTS - LES COULEURS（第 9 课）" if lesson == "L9" else "LA MAISON - LE LOGEMENT（第 10 课）"
            page = 46 if lesson == "L9" else 52
            rows.append({
                "lemma": lemma, "pos": pos, "level": "unverified",
                "level_basis": "推定 A1（教材定位：封面「A1 DÉBUTANT」；前言「niveau faux-débutant」）",
                "topic": topic, "zh": zh, "zh_origin": "supplement", "zh_status": "补充翻译·待核对",
                "fr_def": "", "example_fr": "", "example_zh": "",
                "col": "", "fam": "", "syn": "", "ant": "", "tip": "",
                "note": "列表词汇，教材正文无独立例句；例句译文为补充翻译·待核对",
                "origin": "book",
                "book": "法语词汇渐进初级 Vocabulaire Progressif Du Français Debutant (Claire Miquel).pdf",
                "kind": "lesson", "chapter": chapter,
                "printed_page": page, "pdf_page": page,
                "review": "unreviewed",
            })

# Deduplicate by lemma+pos+chapter
seen = set()
unique = []
for r in rows:
    k = (r["lemma"], r["pos"], r["chapter"])
    if k not in seen:
        seen.add(k)
        unique.append(r)

if unique:
    with open("data/imports/debutant-lesson09-10-fill.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(unique[0].keys()))
        w.writeheader()
        w.writerows(unique)
    print("Wrote", len(unique), "rows")
else:
    print("No rows")
